    perPage?: number;
    /** Optional toast message overrides for CRUD operations */
    messages?: {
        createSuccess?: string;
        createError?: string;
        updateSuccess?: string;
        updateError?: string;
        deleteSuccess?: string;
        deleteError?: string;
        fetchError?: string;
    };
    /** @deprecated Use actionConfig[action].permission */
